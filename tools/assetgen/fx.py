def build_font(out_dir: str) -> dict:
    """Emits font.png (white glyphs on transparent) plus an AngelCode .fnt."""
    chars = sorted(_GLYPHS.keys())
    cols = 12
    rows = (len(chars) + cols - 1) // cols
    cw, ch = GLYPH_W + 1, GLYPH_H + 1
    img = Canvas(cols * cw, rows * ch)
    lines = []
    index = 0
    for i, ch_ in enumerate(chars):
        gx = (i % cols) * cw
        gy = (i // cols) * ch
        pat = _GLYPHS[ch_]
        for y, row in enumerate(pat):
            for x, bit in enumerate(row):
                if bit == "1":
                    img.set(gx + x, gy + y, (255, 255, 255, 255))
        index += 1
        lines.append(f"char id={ord(ch_)} x={gx} y={gy} width={GLYPH_W} height={GLYPH_H} "
                     f"xoffset=0 yoffset=0 xadvance={ADVANCE} page=0 chnl=15")
    save_png(f"{out_dir}/font.png", img)

    # find non-ASCII needed? none. Emit a space glyph too (already in table).
    fnt = []
    fnt.append('info face="RuinDiggerPixel" size=%d bold=0 italic=0 charset="" unicode=1 '
               'stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0 outline=0' % GLYPH_H)
    fnt.append(f'common lineHeight={GLYPH_H + 3} base={GLYPH_H - 1} scaleW={img.w} scaleH={img.h} '
               'pages=1 packed=0 alphaChnl=0 redChnl=0 greenChnl=0 blueChnl=0')
    fnt.append('page id=0 file="font.png"')
    fnt.append(f'chars count={index}')
    fnt.extend(lines)
    with open(f"{out_dir}/font.fnt", "w") as fh:
        fh.write("\n".join(fnt) + "\n")
    return {"glyphs": index, "cell": [GLYPH_W, GLYPH_H], "advance": ADVANCE}
