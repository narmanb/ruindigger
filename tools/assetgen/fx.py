def soft_dot(r: int, color, falloff=2.0) -> Canvas:
    c = Canvas(r * 2, r * 2)
    for y in range(c.h):
        for x in range(c.w):
            dx = (x - r + 0.5) / r
            dy = (y - r + 0.5) / r
            d = math.sqrt(dx * dx + dy * dy)
            if d >= 1.0:
                continue
            a = int(255 * ((1.0 - d) ** falloff))
            c.blend(x, y, (color[0], color[1], color[2], a))
    return c


def chunk(rng: Rng, size: int, color) -> Canvas:
    c = Canvas(size, size)
    pts = [(rng.randint(1, size - 2), rng.randint(1, size - 2)) for _ in range(rng.randint(3, 5))]
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    pts.sort(key=lambda p: math.atan2(p[1] - cy, p[0] - cx))
    c.polygon(pts, color)
    c.set(int(cx), int(cy) - 1, shade(color, 1.3))
    return c


def spark(size: int, color) -> Canvas:
    c = Canvas(size, size)
    m = size // 2
    c.hline(0, size - 1, m, color)
    c.vline(m, 0, size - 1, color)
    c.set(m, m, shade(color, 1.6))
    c.sparkle(m, m, m, (color[0], color[1], color[2], 140))
    return c


def ring(size: int, color) -> Canvas:
    c = Canvas(size, size)
    r = size / 2 - 1
    for a in range(0, 720):
        t = a / 720 * math.tau
        x = size / 2 + math.cos(t) * r
        y = size / 2 + math.sin(t) * r
        c.blend(int(x), int(y), color)
    return c


def smoke_puff(rng: Rng, size: int, color) -> Canvas:
    c = Canvas(size, size)
    for _ in range(rng.randint(4, 7)):
        r = rng.uniform(size * 0.16, size * 0.34)
        x = rng.uniform(r, size - r)
        y = rng.uniform(r, size - r)
        c.ellipse(x, y, r, r, (color[0], color[1], color[2], rng.randint(70, 150)))
    return c


def build_fx(out_dir: str) -> dict:
    rng = Rng(4242)
    sheet = Canvas(64 * 4, 64 * 4)
    cells = {}
    def put(row, col, img):
        sheet.blit(img, col * 64, row * 64)

    put(0, 0, soft_dot(32, (255, 226, 190)))
    put(0, 1, soft_dot(32, (255, 150, 60)))
    put(0, 2, soft_dot(32, (120, 220, 255)))
    put(0, 3, soft_dot(32, (255, 90, 74)))
    for i, col in enumerate([(140, 110, 74), (104, 88, 74), (122, 106, 90), (90, 90, 104)]):
        put(1, i, chunk(rng, 16, col))
    put(2, 0, spark(16, (255, 240, 200)))
    put(2, 1, spark(16, (255, 176, 64)))
    put(2, 2, spark(16, (90, 217, 208)))
    put(2, 3, ring(32, (255, 200, 120, 200)))
    for i in range(4):
        put(3, i, smoke_puff(rng, 32, (150, 140, 130)))
    save_png(f"{out_dir}/fx_sheet.png", sheet)
    meta = {"cell": 64, "soft_white": [0, 0], "soft_warm": [0, 1], "soft_cool": [0, 2],
            "soft_red": [0, 3], "chunk_soil": [1, 0], "chunk_basalt": [1, 1],
            "chunk_alloy": [1, 2], "chunk_metal": [1, 3], "spark": [2, 0],
            "spark_warm": [2, 1], "spark_cool": [2, 2], "ring": [2, 3],
            "smoke": [3, 0]}
    with open(f"{out_dir}/fx_sheet.json", "w") as fh:
        json.dump(meta, fh, indent=1)
    return meta


